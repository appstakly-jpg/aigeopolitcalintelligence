"use client";

import Link from "next/link";
import { useRouter, useSearchParams } from "next/navigation";
import { useRef, useState, type ReactNode } from "react";
import { Badge, Button, Label, Notice, Select, Textarea } from "@/components/ui/primitives";

// Evidence filters offered to the user; the server validates the values again.
const VERIFICATION_FILTERS: Record<string, { label: string; statuses?: string[] }> = {
  all: { label: "Any verification status" },
  strong: { label: "Corroborated or confirmed only", statuses: ["confirmed", "corroborated"] },
  no_weak: { label: "Exclude disputed and unverified", statuses: ["confirmed", "corroborated", "single_source"] },
};
const GRADE_FILTERS: Record<string, string> = { F: "Any source grade", C: "Sources graded A–C", B: "Sources graded A–B" };

export interface ChatCitation { n: number; kind: string; id: string; ref: string | null; title: string; url: string | null; incidentId: string | null; isDemo: boolean }
export interface ChatMessage {
  id: string; role: "user" | "assistant"; content: string; citations?: ChatCitation[] | null; generator?: string | null;
  check?: { ok: boolean; errors: string[]; warnings: string[]; note?: string } | null;
}

function withCitations(text: string, cites: ChatCitation[], msgId: string): ReactNode[] {
  return text.split(/(\[\d{1,3}\])/g).map((part, i) => {
    const m = /^\[(\d{1,3})\]$/.exec(part);
    if (!m) return part;
    const c = cites.find((x) => x.n === Number(m[1]));
    return c ? <a key={i} href={`#${msgId}-c${c.n}`} className="cite" title={c.title}>[{c.n}]</a> : <span key={i} className="text-red-600">[{m[1]}?]</span>;
  });
}

function Answer({ m }: { m: ChatMessage }) {
  const cites = m.citations ?? [];
  const cited = new Set([...m.content.matchAll(/\[(\d{1,3})\]/g)].map((x) => Number(x[1])));
  const lines = m.content.split(/\n+/).filter(Boolean);
  return (
    <div className="grid gap-2">
      <div className="grid gap-1.5 text-sm leading-relaxed">
        {lines.map((l, i) => l.startsWith("- ")
          ? <div key={i} className="ps-3 before:me-1.5 before:content-['•']">{withCitations(l.slice(2), cites, m.id)}</div>
          : <p key={i}>{withCitations(l, cites, m.id)}</p>)}
      </div>
      {cites.filter((c) => cited.has(c.n)).length ? (
        <ol className="grid gap-0.5 border-t pt-2 text-xs">
          {cites.filter((c) => cited.has(c.n)).map((c) => (
            <li key={c.n} id={`${m.id}-c${c.n}`} className="flex flex-wrap items-center gap-1">
              <span className="text-muted-foreground">[{c.n}]</span>
              {c.kind === "incident"
                ? <Link href={`/incidents/${c.id}`} className="text-primary hover:underline">{c.ref}: {c.title}</Link>
                : c.url ? <a href={c.url} target="_blank" rel="noopener noreferrer nofollow" className="text-primary hover:underline">{c.title}</a> : <span>{c.title}</span>}
              {c.kind === "article" && c.incidentId ? <Link href={`/incidents/${c.incidentId}#evidence`} className="text-muted-foreground hover:underline">(incident)</Link> : null}
              {c.isDemo ? <Badge className="border-violet-300 text-violet-700">SYNTHETIC</Badge> : null}
            </li>
          ))}
        </ol>
      ) : null}
      <div className="flex flex-wrap items-center gap-1.5 text-[11px] text-muted-foreground">
        <span>Generated by: {m.generator ?? "—"}</span>
        {m.check ? (m.check.ok ? <span className="text-emerald-700 dark:text-emerald-400">citations checked</span> : <span className="text-red-600">citation check failed</span>) : null}
        {m.check?.warnings?.length ? <span>· {m.check.warnings.join(" ")}</span> : null}
        {m.check?.note ? <span>· {m.check.note}</span> : null}
      </div>
    </div>
  );
}

export function ChatPanel({ sessionId, initial }: { sessionId: string | null; initial: ChatMessage[] }) {
  const [messages, setMessages] = useState<ChatMessage[]>(initial);
  const [sid, setSid] = useState<string | null>(sessionId);
  const [pending, setPending] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [verification, setVerification] = useState("all");
  const [grade, setGrade] = useState("F");
  const formRef = useRef<HTMLFormElement>(null);
  const sp = useSearchParams();
  const router = useRouter();

  async function send(form: FormData) {
    const message = String(form.get("message") ?? "").trim();
    if (message.length < 3) return;
    setPending(true);
    setError(null);
    setMessages((m) => [...m, { id: `local-${Date.now()}`, role: "user", content: message }]);
    try {
      const res = await fetch("/api/chat", {
        method: "POST", headers: { "Content-Type": "application/json" },
        body: JSON.stringify({
          sessionId: sid ?? undefined, message, range: sp.get("range") ?? undefined, from: sp.get("from") ?? undefined, to: sp.get("to") ?? undefined,
          verification: VERIFICATION_FILTERS[verification]?.statuses, minReliability: grade === "F" ? undefined : grade,
        }),
      });
      const data = await res.json();
      if (!res.ok) throw new Error(data.error ?? `Request failed (${res.status})`);
      setMessages((m) => [...m, data.message as ChatMessage]);
      if (!sid) {
        setSid(data.sessionId);
        router.replace(`/analyst?s=${data.sessionId}`, { scroll: false });
      }
      formRef.current?.reset();
    } catch (e) {
      setError(e instanceof Error ? e.message : String(e));
    } finally {
      setPending(false);
    }
  }

  return (
    <div className="grid gap-3">
      <div className="grid gap-3">
        {messages.length === 0 ? (
          <div className="rounded-md border border-dashed p-4 text-sm text-muted-foreground">
            Ask about reported incidents, for example: &ldquo;What has been reported near Bab el-Mandeb this week?&rdquo; or &ldquo;Summarise disputed reports in Saudi Arabia.&rdquo;
            Answers use only stored evidence in the selected date range and cite it.
          </div>
        ) : messages.map((m) => (
          <div key={m.id} className={m.role === "user" ? "ms-auto max-w-[85%] rounded-lg bg-primary px-3 py-2 text-sm text-primary-foreground" : "rounded-lg border bg-card p-3"}>
            {m.role === "user" ? m.content : <Answer m={m} />}
          </div>
        ))}
        {pending ? <div className="rounded-lg border bg-card p-3 text-sm text-muted-foreground">Searching stored evidence…</div> : null}
      </div>
      {error ? <Notice tone="error">{error}</Notice> : null}
      <div className="flex flex-wrap items-end gap-2">
        <Label>Incidents
          <Select value={verification} onChange={(e) => setVerification(e.target.value)} disabled={pending}>
            {Object.entries(VERIFICATION_FILTERS).map(([k, v]) => <option key={k} value={k}>{v.label}</option>)}
          </Select>
        </Label>
        <Label>Source articles
          <Select value={grade} onChange={(e) => setGrade(e.target.value)} disabled={pending}>
            {Object.entries(GRADE_FILTERS).map(([k, v]) => <option key={k} value={k}>{v}</option>)}
          </Select>
        </Label>
        {sid ? <a href={`/api/chat/export?sessionId=${encodeURIComponent(sid)}`} className="ms-auto text-xs text-primary hover:underline">Export conversation (Markdown)</a> : null}
      </div>
      <form ref={formRef} action={send} className="grid gap-2">
        <Textarea name="message" required minLength={3} maxLength={2000} placeholder="Ask about the GCC security picture…" disabled={pending}
          onKeyDown={(e) => { if (e.key === "Enter" && (e.metaKey || e.ctrlKey)) e.currentTarget.form?.requestSubmit(); }} />
        <div className="flex items-center justify-between text-[11px] text-muted-foreground">
          <span>Grounded in your organisation&apos;s stored records. Requests to locate or profile individuals are declined.</span>
          <Button type="submit" disabled={pending}>{pending ? "Working…" : "Ask"}</Button>
        </div>
      </form>
    </div>
  );
}
